// Run with dev server, Edge and playwright-core installed. Uses disposable fixtures.
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { chromium } = require('playwright-core');
const { createClient } = require('@supabase/supabase-js');
require('@next/env').loadEnvConfig(process.cwd());
const client = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SECRET_KEY, { auth: { persistSession: false } });
const baseURL = process.env.TEST_BASE_URL || 'http://127.0.0.1:3000';
let adminId, examId, browser;
const checks = [];
async function db(query) { const result = await query; if (result.error) throw new Error('Fixture query failed: ' + result.error.code); return result; }
async function main() {
  const token = crypto.randomUUID();
  const email = 'prepx-subject-test-' + token + '@example.com';
  const password = crypto.randomBytes(24).toString('base64url') + '!aA1';
  const auth = await client.auth.admin.createUser({ email, password, email_confirm: true });
  if (auth.error) throw new Error('Test account creation failed.');
  adminId = auth.data.user.id;
  await db(client.from('admin_profiles').insert({ user_id: adminId }));
  examId = (await db(client.from('examinations').insert({ name: 'Subject Test ' + token, year: 2027, status: 'DRAFT' }).select('id').single())).data.id;
  const published = (await db(client.from('examinations').select('id').eq('year', 2026).eq('status', 'PUBLISHED').order('id').limit(1).single())).data;
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.setDefaultTimeout(45000);
  page.setDefaultNavigationTimeout(120000);
  await page.goto(baseURL + '/admin/login');
  await page.getByLabel('Email Address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.waitForURL('**/admin/dashboard', { timeout: 120000 });
  await page.goto(baseURL + '/admin/subjects');
  await page.getByText('Select an examination above to manage its subjects.', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Add Subject', exact: true }).count(), 0);
  checks.push('1: no-exam selector and empty state');
  await page.getByRole('combobox', { name: 'Examination:', exact: true }).selectOption(published.id);
  await page.waitForURL('**/admin/subjects?examId=' + published.id);
  await page.getByText('This examination is published.', { exact: false }).waitFor();
  const publishedRows = (await db(client.from('subjects').select('id').eq('examination_id', published.id))).data;
  assert.ok(publishedRows.length >= 8);
  assert.equal(await page.locator('tbody tr').count(), publishedRows.length);
  const controls = page.locator('tbody button');
  for (let i = 0; i < await controls.count(); i++) assert.ok(await controls.nth(i).isDisabled());
  checks.push('2: seeded published exam, subjects and disabled controls');
  await page.goto(baseURL + '/admin/subjects?examId=' + examId);
  await page.getByText('No subjects yet. Add subjects to start managing grades.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Add First Subject', exact: true }).waitFor();
  checks.push('3: empty draft examination');
  const dialog = () => page.getByRole('dialog');
  const row = name => page.locator('tbody tr').filter({ has: page.getByRole('rowheader').filter({ hasText: name }) });
  async function add(name, code, required = true) {
    await page.getByRole('button', { name: 'Add Subject', exact: true }).click();
    await dialog().getByLabel('Subject Name', { exact: true }).fill(name);
    await dialog().getByLabel('Subject Code (Optional)', { exact: true }).fill(code);
    if (!required) await dialog().getByRole('switch', { name: 'Required Subject', exact: true }).click();
    await dialog().getByRole('button', { name: 'Add Subject', exact: true }).click();
    await dialog().waitFor({ state: 'hidden' });
    await row(name).waitFor();
  }
  await page.getByRole('button', { name: 'Add First Subject', exact: true }).click();
  await dialog().getByRole('button', { name: 'Add Subject', exact: true }).click();
  await dialog().getByText('Subject name is required.', { exact: true }).waitFor();
  await dialog().getByLabel('Subject Name', { exact: true }).fill('Tamil');
  await dialog().getByLabel('Subject Code (Optional)', { exact: true }).fill('ABCDEFGHIJK');
  await dialog().getByRole('button', { name: 'Add Subject', exact: true }).click();
  await dialog().getByText('Subject code must be under 10 characters.', { exact: true }).waitFor();
  await dialog().getByLabel('Subject Code (Optional)', { exact: true }).fill('tml');
  await dialog().getByRole('button', { name: 'Add Subject', exact: true }).click();
  await dialog().waitFor({ state: 'hidden' });
  await row('Tamil').getByText('TML', { exact: true }).waitFor();
  await add('English', 'ENG');
  await add('Mathematics', 'MAT');
  await add('Science', 'SCI', false);
  await page.getByText('4 subjects · 4 active · 3 required', { exact: true }).waitFor();
  checks.push('4: repeated modal opening, validation, four ordered subjects and normalized codes');
  await page.getByRole('button', { name: 'Edit English', exact: true }).click();
  assert.equal(await dialog().getByLabel('Subject Name', { exact: true }).inputValue(), 'English');
  assert.equal(await dialog().getByRole('switch', { name: 'Required Subject', exact: true }).getAttribute('aria-checked'), 'true');
  await dialog().getByLabel('Subject Name', { exact: true }).fill('English Language');
  await dialog().getByRole('button', { name: 'Save Changes', exact: true }).click();
  await dialog().waitFor({ state: 'hidden' });
  await row('English Language').waitFor();
  checks.push('5: edit prefilled subject and preserve required state');
  await page.getByRole('button', { name: 'Move Mathematics up', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('tbody tr')[1]?.textContent.includes('Mathematics'));
  await page.getByRole('button', { name: 'Move Tamil down', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('tbody tr')[0]?.textContent.includes('Mathematics'));
  assert.ok(await page.getByRole('button', { name: 'Move Mathematics up', exact: true }).isDisabled());
  assert.ok(await page.getByRole('button', { name: 'Move Science down', exact: true }).isDisabled());
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('tbody tr')[0]?.textContent.includes('Mathematics'));
  const ordered = (await db(client.from('subjects').select('subject_name,display_order').eq('examination_id', examId).order('display_order'))).data;
  assert.deepEqual(ordered.map(s => s.subject_name), ['Mathematics','Tamil','English Language','Science']);
  assert.deepEqual(ordered.map(s => s.display_order), [0,1,2,3]);
  checks.push('6: up/down ordering, boundary buttons, sequential DB order and reload persistence');
  await page.getByRole('switch', { name: 'Science active', exact: true }).click();
  await page.getByText('4 subjects · 3 active · 3 required', { exact: true }).waitFor();
  assert.equal(await page.getByRole('switch', { name: 'Science active', exact: true }).getAttribute('aria-checked'), 'false');
  await page.getByRole('switch', { name: 'Science active', exact: true }).click();
  await page.getByText('4 subjects · 4 active · 3 required', { exact: true }).waitFor();
  checks.push('7: active toggle in both directions');
  await page.getByRole('button', { name: 'Edit Science', exact: true }).click();
  assert.equal(await dialog().getByRole('switch', { name: 'Required Subject', exact: true }).getAttribute('aria-checked'), 'false');
  await dialog().getByRole('switch', { name: 'Required Subject', exact: true }).click();
  await dialog().getByRole('button', { name: 'Save Changes', exact: true }).click();
  await dialog().waitFor({ state: 'hidden' });
  await page.getByText('4 subjects · 4 active · 4 required', { exact: true }).waitFor();
  checks.push('8: required/optional badges and saved required toggle');
  await page.getByRole('button', { name: 'Delete Tamil', exact: true }).click();
  await dialog().waitFor();
  assert.equal(await dialog().getByText(/grade entr.*will also/).count(), 0);
  await dialog().getByRole('button', { name: 'Cancel', exact: true }).click();
  await row('Tamil').waitFor();
  await page.getByRole('button', { name: 'Delete Tamil', exact: true }).click();
  await dialog().getByRole('button', { name: 'Delete Subject', exact: true }).click();
  await dialog().waitFor({ state: 'hidden' });
  await page.getByText('3 subjects · 3 active · 3 required', { exact: true }).waitFor();
  assert.equal(await row('Tamil').count(), 0);
  checks.push('9: no-grade confirmation, cancellation and permanent deletion');
  checks.push('10: accurate footer counts after add, toggle, edit and delete');
  const science = (await db(client.from('subjects').select('id').eq('examination_id', examId).eq('subject_name','Science').single())).data;
  const student = (await db(client.from('students').insert({ examination_id: examId, full_name: 'Subject Test Student', school_name: 'Test School', index_number: 'SUBJECTTEST' }).select('id').single())).data;
  await db(client.from('student_results').insert({ subject_id: science.id, student_id: student.id, grade: 'A' }));
  await page.reload();
  await page.getByRole('button', { name: 'Delete Science', exact: true }).click();
  await dialog().getByText('1 grade entry will also be permanently deleted.', { exact: true }).waitFor();
  await dialog().getByRole('button', { name: 'Delete Subject', exact: true }).click();
  await dialog().waitFor({ state: 'hidden' });
  await page.getByText('2 subjects · 2 active · 2 required', { exact: true }).waitFor();
  assert.equal((await db(client.from('student_results').select('id').eq('subject_id', science.id))).data.length, 0);
  const logs = (await db(client.from('audit_logs').select('action').eq('admin_id', adminId))).data.map(log => log.action);
  for (const action of ['SUBJECT_CREATED','SUBJECT_UPDATED','SUBJECT_REORDERED','SUBJECT_DELETED']) assert.ok(logs.includes(action));
  await page.setViewportSize({ width: 375, height: 812 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: 'Add Subject', exact: true }).click();
  await dialog().getByLabel('Subject Name', { exact: true }).fill('Canceled subject');
  await page.keyboard.press('Escape');
  await dialog().waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Add Subject', exact: true }).click();
  assert.equal(await dialog().getByLabel('Subject Name', { exact: true }).inputValue(), '');
  await dialog().getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.goto(baseURL + '/admin/subjects?examId=invalid');
  await page.getByText('Examination not found. Please select a valid examination.', { exact: true }).waitFor();
  checks.push('Extra: grade-loss warning/cascade, audit events, narrow layout, Escape/reset, invalid exam');
  console.log('PASS:\n' + checks.join('\n'));
}
main().catch(error => { console.error('Completed:', checks); console.error(error); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  if (examId) await db(client.from('examinations').delete().eq('id', examId));
  if (adminId) { const { error } = await client.auth.admin.deleteUser(adminId); if (error) { console.error('Test admin cleanup failed'); process.exitCode = 1; } }
});
